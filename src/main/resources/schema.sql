-- ============================ 对象级授权（多租户只读账号的数据权限） ============================
-- 角色为 TENANT_VIEWER 的账号只能看到被显式授权的对象；TENANT_ADMIN 可见本租户全部对象。
-- 授权按业务对象粒度发放（这里以井组 WELL_GROUP 为授权单元，下级试验段/批次随井组收敛）。
CREATE TABLE IF NOT EXISTS t_object_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    grantee_account VARCHAR(64) NOT NULL,     -- 被授权账号
    object_type VARCHAR(32) NOT NULL,         -- 如 WELL_GROUP
    object_id BIGINT NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_object_grant UNIQUE (tenant_id, grantee_account, object_type, object_id)
);

-- ============================ 秒级井口遥测（独立于业务读数的高频事件流） ============================
-- 约 150000 条秒级数据。partition_date 为 reading_time 派生的分区裁剪键（生成列），
-- 聚合查询必须带 partition_date 范围谓词，禁止扫描全表。
CREATE TABLE IF NOT EXISTS t_wellhead_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    well_group_id BIGINT NOT NULL,
    test_section_id BIGINT NOT NULL,
    monitor_point_id BIGINT NOT NULL,
    reading_time TIMESTAMP NOT NULL,           -- 秒级采样时刻
    partition_date DATE GENERATED ALWAYS AS (CAST(reading_time AS DATE)),  -- 日期分区裁剪键
    pressure_mpa DECIMAL(10,3) NOT NULL,       -- 井口压力
    temperature_c DECIMAL(10,3),
    flow_m3h DECIMAL(12,3),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------- 索引：运营检索（确定性主键分页 + 组合条件） ----------------
