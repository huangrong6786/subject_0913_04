-- ============================================================================
-- 井口监测时序规则（峰 / 平 / 谷）版本化与试验窗口规则计算（第四期）
--
-- 设计要点：
--  1) 规则链 t_tou_rule_chain 绑定对象（监测点 / 井组）；链上每个版本 t_tou_rule_set
--     携带生效窗口 [effective_from, effective_to)（左闭右开）、压力阈值与区间集合。
--  2) 规则一旦 ENABLED 即冻结：区间行与冻结快照不可原地修改，业务变更只能新建新版本；
--     旧版本在新版本生效时刻闭合为 SUPERSEDED，历史计算永远引用当时版本。
--  3) 区间按“一天 1440 分钟圆环”定义 [start_minute, end_minute)，允许跨午夜（start>end）；
--     启用前强制校验：区间两两不得重叠、必须完整覆盖 1440 分钟、峰/平/谷三类齐备。
--  4) 试验窗口按井场时区（t_well_group.timezone）左闭右开切分，跨午夜班次只计量一次；
--     同一对象已算窗口与新窗口重叠（左闭右开相交）直接拒绝，杜绝重复计量。
--  5) 压力阈值按每条观测的观测时刻选生效版本，明细保留 rule_set_id/version_no/阈值快照；
--     累计金额（回灌量 × 时段系数）全程 BigDecimal 精确运算，仅最终合计统一 HALF_UP 舍入。
--  6) 结果头对 (tenant_id, target_type, target_id, window_start, window_end) 建唯一索引，
--     并发重放/重算由数据库兜底，绝不会产生两份结果。
-- ============================================================================

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('geothermal-4', '井口监测时序规则（峰平谷）版本化与试验窗口规则计算');

-- 井场时区：对象级业务时区，观测归类与试验窗口均按此时区解释
ALTER TABLE t_well_group ADD COLUMN IF NOT EXISTS timezone VARCHAR(48) NOT NULL DEFAULT 'Asia/Shanghai';

-- ============================ 时序规则链（一个对象一条链，链上多版本） ============================
CREATE TABLE IF NOT EXISTS t_tou_rule_chain (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    chain_code VARCHAR(32) NOT NULL,         -- 规则链业务编码，租户内唯一
    chain_name VARCHAR(64) NOT NULL,
    target_type VARCHAR(16) NOT NULL,        -- MONITOR_POINT / WELL_GROUP
    target_id BIGINT NOT NULL,               -- 监测点 id 或井组 id
    current_version_id BIGINT,               -- 当前生效版本（null 表示尚无启用版本）
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    version INT NOT NULL DEFAULT 0,          -- 乐观锁：串行化同链并发启用
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tou_chain_code UNIQUE (tenant_id, chain_code)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tou_chain_target ON t_tou_rule_chain (tenant_id, target_type, target_id);

-- ============================ 规则版本（峰平谷区间 + 压力阈值的不可变快照单元） ============================
CREATE TABLE IF NOT EXISTS t_tou_rule_set (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    chain_id BIGINT NOT NULL,
    version_no INT NOT NULL,                 -- 链上从 1 递增的版本号
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT', -- DRAFT/ENABLED/SUPERSEDED
    effective_from TIMESTAMP NOT NULL,       -- 生效起点（含），按对象时区解释
    effective_to TIMESTAMP,                  -- 生效终点（不含）；null 表示开放区间，新版本启用时闭合
    pressure_threshold_mpa DECIMAL(10,3) NOT NULL, -- 井口压力阈值（按观测时刻选版本）
    frozen_snapshot CLOB,                    -- 启用时冻结的规则要素快照（区间/系数/阈值 JSON），永不再改
    remark VARCHAR(255),
    freeze_time TIMESTAMP,                   -- 启用冻结时刻
    freeze_by BIGINT,
    version INT NOT NULL DEFAULT 0,          -- 乐观锁
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tou_rule_set_version UNIQUE (chain_id, version_no),
    CONSTRAINT fk_tou_set_chain FOREIGN KEY (chain_id) REFERENCES t_tou_rule_chain(id)
);
CREATE INDEX IF NOT EXISTS idx_tou_set_chain_status ON t_tou_rule_set (chain_id, status, effective_from);
CREATE INDEX IF NOT EXISTS idx_tou_set_tenant ON t_tou_rule_set (tenant_id, status);

-- ============================ 规则区间（峰/平/谷业务区间，左闭右开，允许跨午夜） ============================
CREATE TABLE IF NOT EXISTS t_tou_interval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    rule_set_id BIGINT NOT NULL,             -- 所属规则版本（仅 DRAFT 可写；ENABLED 后永不修改/删除）
    interval_code VARCHAR(32) NOT NULL,      -- 区间编码（PEAK_AM/FLAT/VALLEY...），版本内唯一
    segment_type VARCHAR(16) NOT NULL,       -- PEAK 峰值 / FLAT 平段 / VALLEY 谷值
    start_minute INT NOT NULL,               -- 起点分钟 [0,1440)（含）
    end_minute INT NOT NULL,                 -- 终点分钟 [0,1440]（不含）；end<=start 表示跨午夜
    price_coefficient DECIMAL(12,6) NOT NULL,-- 时段系数（峰加价/谷优惠）
    seq_no INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tou_interval_code UNIQUE (rule_set_id, interval_code),
    CONSTRAINT fk_tou_interval_set FOREIGN KEY (rule_set_id) REFERENCES t_tou_rule_set(id)
);
CREATE INDEX IF NOT EXISTS idx_tou_interval_set ON t_tou_interval (rule_set_id);

-- ============================ 时序规则计算结果头（一次试验窗口计算一行，并发重算唯一） ============================
CREATE TABLE IF NOT EXISTS t_tou_calc_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    calc_no VARCHAR(64) NOT NULL,            -- 计算单号（唯一业务键）
    target_type VARCHAR(16) NOT NULL,        -- MONITOR_POINT / WELL_GROUP
    target_id BIGINT NOT NULL,
    window_start TIMESTAMP NOT NULL,         -- 试验窗口起点（井场时区，含）
    window_end TIMESTAMP NOT NULL,           -- 试验窗口终点（井场时区，不含）
    window_timezone VARCHAR(48) NOT NULL,    -- 试验窗口采用的井场时区
    rule_chain_id BIGINT NOT NULL,
    observation_count INT NOT NULL DEFAULT 0,
    total_scaled_injection_m3 DECIMAL(16,3), -- 分时段回灌量合计（全程精确累加，仅此最终值统一舍入）
    rounding_scale INT NOT NULL DEFAULT 3,
    rounding_mode VARCHAR(16) NOT NULL DEFAULT 'HALF_UP',
    status VARCHAR(16) NOT NULL DEFAULT 'CALCULATED',
    calc_snapshot CLOB,                      -- 计算快照：逐版本冻结规则（区间/系数/阈值/生效窗口）
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 同一对象同一左闭右开窗口的计算只有一份：幂等返回 + 并发唯一兜底
    CONSTRAINT uk_tou_calc_no UNIQUE (calc_no),
    CONSTRAINT uk_tou_calc_window UNIQUE (tenant_id, target_type, target_id, window_start, window_end),
    CONSTRAINT fk_tou_calc_chain FOREIGN KEY (rule_chain_id) REFERENCES t_tou_rule_chain(id)
);
CREATE INDEX IF NOT EXISTS idx_tou_calc_target_window ON t_tou_calc_result (tenant_id, target_type, target_id, window_start);

-- ============================ 计算明细（每条观测归入哪个版本哪个区间，逐行快照） ============================
CREATE TABLE IF NOT EXISTS t_tou_calc_detail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calc_result_id BIGINT NOT NULL,
    observation_id BIGINT NOT NULL,
    observed_at TIMESTAMP NOT NULL,          -- 观测时刻（对象时区本地时刻）
    biz_date DATE NOT NULL,                  -- 观测业务日期（对象时区派生）
    segment_type VARCHAR(16) NOT NULL,       -- PEAK / FLAT / VALLEY
    interval_code VARCHAR(32) NOT NULL,
    start_minute INT NOT NULL,
    end_minute INT NOT NULL,
    day_offset INT NOT NULL DEFAULT 0,       -- 跨午夜区间实例相对业务日期的偏移（谷段 00:30 归属前一日启动的实例 => -1）
    segment_start TIMESTAMP NOT NULL,        -- 归入的区间实例起点（本地时刻）
    segment_end TIMESTAMP NOT NULL,          -- 归入的区间实例终点（不含）
    rule_set_id BIGINT NOT NULL,             -- 采用的规则版本（历史明细永久保留）
    rule_version_no INT NOT NULL,
    raw_injection_volume_m3 DECIMAL(14,3) NOT NULL,  -- 原始回灌量
    price_coefficient DECIMAL(12,6) NOT NULL,        -- 当时版本该区间系数
    scaled_injection_m3 DECIMAL(20,9) NOT NULL,      -- 原始量×系数（精确，不舍入）
    pressure_mpa DECIMAL(10,3) NOT NULL,
    pressure_threshold_mpa DECIMAL(10,3) NOT NULL,   -- 当时版本压力阈值快照
    threshold_breached BOOLEAN NOT NULL DEFAULT FALSE, -- 压力是否超阈（pressure > threshold）
    detail_snapshot CLOB,                    -- 逐行计算快照（版本/区间/阈值/时区 JSON）
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 同一结果内每条观测只出现一次：跨午夜班次不重复计量
    CONSTRAINT uk_tou_calc_detail_obs UNIQUE (calc_result_id, observation_id),
    CONSTRAINT fk_tou_detail_result FOREIGN KEY (calc_result_id) REFERENCES t_tou_calc_result(id),
    CONSTRAINT fk_tou_detail_obs FOREIGN KEY (observation_id) REFERENCES t_wellhead_observation(id),
    CONSTRAINT fk_tou_detail_set FOREIGN KEY (rule_set_id) REFERENCES t_tou_rule_set(id)
);
CREATE INDEX IF NOT EXISTS idx_tou_detail_result ON t_tou_calc_detail (calc_result_id, observed_at);
CREATE INDEX IF NOT EXISTS idx_tou_detail_version ON t_tou_calc_detail (rule_set_id);
