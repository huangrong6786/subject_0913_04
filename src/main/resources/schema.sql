-- ============================ 导入文件（一次上传 = 一个导入任务） ============================
CREATE TABLE IF NOT EXISTS t_import_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    checksum VARCHAR(64) NOT NULL,            -- 文件内容 SHA-256，文件级幂等键
    content BLOB,                             -- 原始文件内容：断点续传/失败分片重试的数据源
    shard_size INT NOT NULL,                  -- 本分片计划的行数粒度
    total_rows INT NOT NULL DEFAULT 0,        -- 数据行总数（不含表头）
    success_rows INT NOT NULL DEFAULT 0,
    updated_rows INT NOT NULL DEFAULT 0,
    failed_rows INT NOT NULL DEFAULT 0,
    total_shards INT NOT NULL DEFAULT 0,
    done_shards INT NOT NULL DEFAULT 0,
    failed_shards INT NOT NULL DEFAULT 0,
    status VARCHAR(24) NOT NULL DEFAULT 'PROCESSING', -- PROCESSING/COMPLETED/COMPLETED_WITH_ERRORS/FAILED
    message VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_import_file_checksum UNIQUE (tenant_id, checksum)
);

-- ============================ 导入分片（断点续传 / 失败重试的最小单元） ============================
CREATE TABLE IF NOT EXISTS t_import_shard (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_file_id BIGINT NOT NULL,
    shard_index INT NOT NULL,                 -- 0 起始的分片序号
    row_start INT NOT NULL,                   -- 覆盖的原始行号区间 [row_start, row_end]（含表头偏移）
    row_end INT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING', -- PENDING/PROCESSING/SUCCESS/FAILED
    attempt_count INT NOT NULL DEFAULT 0,
    success_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    error_message VARCHAR(512),               -- 分片级失败原因（基础设施异常；行级失败不算分片失败）
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_import_shard_idx UNIQUE (import_file_id, shard_index),
    CONSTRAINT fk_shard_file FOREIGN KEY (import_file_id) REFERENCES t_import_file(id)
);

-- ============================ 逐行明细（成功/更新/失败 + 原始行号/字段/原值/原因） ============================
CREATE TABLE IF NOT EXISTS t_import_row (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_file_id BIGINT NOT NULL,
    shard_id BIGINT NOT NULL,
    row_no INT NOT NULL,                      -- 原始 CSV 物理行号（表头为第 1 行）
    object_code VARCHAR(64),
    serial_no VARCHAR(64),
    observed_at_raw VARCHAR(64),              -- 观测时间原始文本
    result VARCHAR(16) NOT NULL,              -- SUCCESS/UPDATED/FAILED
    fail_field VARCHAR(32),                   -- 失败字段（校验失败的列名）
    fail_value VARCHAR(255),                  -- 失败字段原始值
    fail_reason VARCHAR(512),                 -- 失败原因
    biz_key VARCHAR(255),                     -- 业务键（objectCode + serialNo）
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_import_row_no UNIQUE (import_file_id, row_no),  -- 行级幂等：分片重试不重复落明细
    CONSTRAINT fk_row_file FOREIGN KEY (import_file_id) REFERENCES t_import_file(id),
    CONSTRAINT fk_row_shard FOREIGN KEY (shard_id) REFERENCES t_import_shard(id)
);

-- ============================ 井口观测数据（CSV 导入落库目标表） ============================
-- 业务键：(tenant_id, monitor_point_id, serial_no) —— 井口网关重发同序列号时幂等更新；
--          (tenant_id, monitor_point_id, observed_at) —— 同监测点同一观测时刻唯一。
CREATE TABLE IF NOT EXISTS t_wellhead_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
