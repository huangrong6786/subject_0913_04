    source_device VARCHAR(64) NOT NULL,       -- 来源设备
    observed_at TIMESTAMP NOT NULL,           -- 观测时间（业务时区本地时刻）
    biz_date DATE NOT NULL,                   -- 业务日期（observed_at 派生，跨天补报按观测日落账）
    pressure_mpa DECIMAL(10,3) NOT NULL,      -- 井口压力（MPa）
    temperature_c DECIMAL(10,3) NOT NULL,     -- 温度（℃）
    flow_m3h DECIMAL(12,3) NOT NULL,          -- 流量（m³/h）
    injection_volume_m3 DECIMAL(14,3) NOT NULL, -- 回灌量（m³）
    import_file_id BIGINT NOT NULL,           -- 最近一次写入来源
    row_no INT NOT NULL,
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_obs_point_serial UNIQUE (tenant_id, monitor_point_id, serial_no),
    CONSTRAINT uk_obs_point_time UNIQUE (tenant_id, monitor_point_id, observed_at),
    CONSTRAINT fk_obs_point FOREIGN KEY (monitor_point_id) REFERENCES t_monitor_point(id),
    CONSTRAINT fk_obs_file FOREIGN KEY (import_file_id) REFERENCES t_import_file(id)
